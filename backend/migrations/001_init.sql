CREATE TABLE users (
    id            INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL CHECK (char_length(btrim(username)) >= 1),
    email         VARCHAR(255) NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- id film diisi eksplisit oleh seeder (1..20) karena movie_id dari UI dan Gemini
-- bergantung padanya, maka BY DEFAULT (bukan ALWAYS). Seeder wajib menyetel ulang sequence.
CREATE TABLE movies (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(255) NOT NULL,
    year         SMALLINT     NOT NULL CHECK (year BETWEEN 1888 AND 2100),
    director     VARCHAR(255) NOT NULL,
    rating       NUMERIC(3,1) NOT NULL CHECK (rating BETWEEN 0 AND 10),
    duration     VARCHAR(50)  NOT NULL,
    synopsis     TEXT         NOT NULL,
    poster_url   TEXT         NOT NULL,
    cast_members TEXT[]       NOT NULL DEFAULT '{}'
);

CREATE TABLE genres (
    id   SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE movie_genres (
    movie_id INT      NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    genre_id SMALLINT NOT NULL REFERENCES genres(id) ON DELETE RESTRICT,
    PRIMARY KEY (movie_id, genre_id)
);

-- PK sudah melayani pencarian per film; index ini melayani filter per genre.
CREATE INDEX movie_genres_genre_id_idx ON movie_genres (genre_id);

CREATE TABLE watchlist (
    user_id    INT         NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
    movie_id   INT         NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, movie_id)
);

CREATE INDEX watchlist_movie_id_idx ON watchlist (movie_id);

CREATE TABLE reviews (
    id         INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id    INT         NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
    -- RESTRICT: ulasan adalah konten buatan user, jangan hilang diam-diam
    -- kalau sebuah film dihapus.
    movie_id   INT         NOT NULL REFERENCES movies(id) ON DELETE RESTRICT,
    rating     SMALLINT    NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review     TEXT        NOT NULL CHECK (char_length(btrim(review)) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, movie_id)
);

CREATE INDEX reviews_movie_id_idx ON reviews (movie_id);
